age = 19 # Integer
per = 98.9 # Float
is_male = True # Boolean

print(f"Hello! {name}   Type: {type(name)}")
print(f"Your age is {age}   Type: {type(age)}")
print(f"Your percentage is {per}   Type: {type(per)}")
print(f"Is_Male: {is_male}   Type: {type(is_male)}")
